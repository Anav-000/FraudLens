import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { AnalysisResultView } from "../features/analysis/AnalysisResultView";
import { TextAnalysisResponse } from "../types/api";

describe("AnalysisResultView Component", () => {
  const sampleWarningResult: TextAnalysisResponse = {
    assessment: "warning_signs_found",
    category: "job",
    summary: "This message demands an advance fee for a remote job offer.",
    warning_signs: [
      {
        title: "Advance Fee Requirement",
        evidence_quote: "Please deposit $150 to https://pay.example.invalid/register to secure your interview.",
        explanation: "Legitimate employers do not charge candidate onboarding or registration fees.",
      },
    ],
    uncertainties: ["The sender company name cannot be verified from message body alone."],
    verification_steps: [
      "Contact the company directly using official contact information on their authentic website.",
    ],
    language: "en",
    analysis_basis: "submitted_text_only",
    external_checks_performed: false,
    limitation: "Automated analysis generated by an AI model based solely on the submitted text.",
  };

  it("renders warning signs, category, summary, and verification steps", () => {
    render(<AnalysisResultView result={sampleWarningResult} />);

    expect(screen.getByText(/Warning Signs Detected/i)).toBeInTheDocument();
    expect(screen.getByText(/Job \/ Employment Offer/i)).toBeInTheDocument();
    expect(screen.getByText(/This message demands an advance fee/i)).toBeInTheDocument();
    expect(screen.getByText(/Advance Fee Requirement/i)).toBeInTheDocument();
    expect(screen.getByText(/Legitimate employers do not charge/i)).toBeInTheDocument();
    expect(screen.getByText(/Contact the company directly/i)).toBeInTheDocument();
    expect(screen.getByText(/Analysis Basis:/i)).toBeInTheDocument();
  });

  it("renders evidence quotes strictly as plain text and NEVER as clickable links", () => {
    render(<AnalysisResultView result={sampleWarningResult} />);

    // Check evidence quote text is present
    expect(
      screen.getByText(/Please deposit \$150 to https:\/\/pay\.example\.invalid\/register/i)
    ).toBeInTheDocument();

    // Verify there are NO <a> tags rendered anywhere for URLs
    const links = screen.queryAllByRole("link");
    expect(links).toHaveLength(0);

    // Verify the quote container is a blockquote
    const quoteEl = screen.getByText(/Please deposit \$150 to https:\/\/pay\.example\.invalid\/register/i);
    expect(quoteEl.closest("blockquote")).not.toBeNull();
  });

  it("renders explicit disclaimer when no clear warning signs are found", () => {
    const noClearSignsResult: TextAnalysisResponse = {
      assessment: "no_clear_warning_signs",
      category: "unclear",
      summary: "The submitted message contains standard conversational phrasing.",
      warning_signs: [],
      uncertainties: ["Sender authenticity cannot be confirmed."],
      verification_steps: ["Confirm via established out-of-band communication channels."],
      language: "en",
      analysis_basis: "submitted_text_only",
      external_checks_performed: false,
      limitation: "Automated analysis generated by an AI model based solely on the submitted text.",
    };

    render(<AnalysisResultView result={noClearSignsResult} />);

    expect(screen.getByText(/No Clear Warning Signs Found/i)).toBeInTheDocument();
    // Verify explicit disclaimer requirement
    expect(
      screen.getByText(/Important: This does not prove the message or sender is legitimate/i)
    ).toBeInTheDocument();
    expect(screen.queryByText(/Identified Warning Signs/i)).toBeNull();
  });

  it("renders insufficient information badge and message", () => {
    const insufficientResult: TextAnalysisResponse = {
      assessment: "insufficient_information",
      category: "unclear",
      summary: "The text is too brief to evaluate.",
      warning_signs: [],
      uncertainties: ["Context is entirely missing."],
      verification_steps: ["Request verified context from known channels."],
      language: "en",
      analysis_basis: "submitted_text_only",
      external_checks_performed: false,
      limitation: "Automated analysis generated by an AI model based solely on the submitted text.",
    };

    render(<AnalysisResultView result={insufficientResult} />);

    expect(screen.getByText(/Insufficient Information/i)).toBeInTheDocument();
    expect(screen.getByText(/Message Lacks Context for Assessment/i)).toBeInTheDocument();
  });

  it("displays stale indicator when input was modified after analysis", () => {
    render(<AnalysisResultView result={sampleWarningResult} isStale={true} />);

    expect(
      screen.getByText(/Text or language was modified/i)
    ).toBeInTheDocument();
  });

  it("triggers onClear callback when Clear Result button is clicked", async () => {
    const user = userEvent.setup();
    const handleClear = vi.fn();

    render(<AnalysisResultView result={sampleWarningResult} onClear={handleClear} />);

    const clearButton = screen.getByRole("button", { name: /Clear Result/i });
    await user.click(clearButton);

    expect(handleClear).toHaveBeenCalledTimes(1);
  });

  it("renders category label 'Other / General Message' for 'other' category", () => {
    const otherResult: TextAnalysisResponse = {
      ...sampleWarningResult,
      category: "other",
    };
    render(<AnalysisResultView result={otherResult} />);
    expect(screen.getByText("Other / General Message")).toBeInTheDocument();
  });
});
